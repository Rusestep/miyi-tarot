const pad = (value: number) => String(value).padStart(2, "0");

const makeMajorCards = (): TarotCard[] =>
  majors.map(([englishName, name, upright, reversed, guidance], index) => ({
    id: `major-${pad(index)}`,
    number: index === 0 ? "0" : toRoman(index),
    name,
    englishName,
    group: "major",
    groupName: "大阿尔卡那",
    image: `/cards/m${pad(index)}.webp`,
    upright,
    reversed,
    guidance,
  }));

const makeSuitCards = (
  key: "wands" | "cups" | "swords" | "pentacles",
  filePrefix: "w" | "c" | "s" | "p",
  groupName: string,
  meanings: CardMeaning[],
): TarotCard[] =>
  meanings.map(([englishName, name, upright, reversed, guidance], index) => ({
    id: `${key}-${pad(index + 1)}`,
    number: index < 10 ? String(index + 1) : ["侍从", "骑士", "王后", "国王"][index - 10],
    name,
    englishName,
    group: key,
    groupName,
    image: `/cards/${filePrefix}${pad(index + 1)}.webp`,
    upright,
    reversed,
    guidance,
  }));

function toRoman(value: number) {
  const pairs: [number, string][] = [
    [10, "X"],
    [9, "IX"],
    [5, "V"],
    [4, "IV"],
    [1, "I"],
  ];
  let result = "";
  let remaining = value;
  for (const [amount, symbol] of pairs) {
    while (remaining >= amount) {
      result += symbol;
      remaining -= amount;
    }
  }
  return result;
}

